"""Author the eval itself as a Harbor task, dogfooding ``eval_harvest.harbor``'s task-shape knowledge.

The eval *is* a Harbor task: its environment clones the objective's repo at the pinned SHA and
editable-installs ``eval_harvest`` (``uv pip install -e .``), and its instruction tells the
agent-under-test to build PR-review datapoints with the ``eval-harvest`` CLI, reading its
``--help`` / man pages — and **nothing else**. No methodology goes in the prompt: coaching the agent
would test the prompt, not the CLI's docs (PRD §4, G-1 What To Build §2), and it must not name the
datapoint kind or the verdict.

The assembled directory is validated with the very ``Harbor.validate_task_config`` /
``Harbor.validate_task_layout`` the emitter uses, so a shape Harbor would reject fails here at
materialize time rather than at ``harbor run``. This module *uses* the shipped package (``eval/`` may
import ``eval_harvest``); the reverse — the package importing ``eval/`` — is what S-18 forbids.
"""

from __future__ import annotations

import shutil
from pathlib import Path

from eval.models import Objective
from eval_harvest.harbor import (
    TASK_SCHEMA_VERSION,
    CompiledTask,
    EmittedFile,
    Harbor,
)
from eval_harvest.tomlw import TomlFloat, TomlValue, emit_document

#: The repo root, from which the bundled ``eval_harvest`` source is copied into the build context.
#: ``eval/`` lives at the repo root, so its parent is the root (``src/`` and ``pyproject.toml`` there).
_REPO_ROOT: Path = Path(__file__).parents[1]

#: The agent-environment base image. It must provide git (to clone the repo), gh (the CLI's forge
#: client, used by survey/capture), and uv (to editable-install the package). Pinned, Linux (NFR-8).
_AGENT_BASE_IMAGE = "python:3.12-bookworm"
#: The verifier base image. The eval's real grading is external (see ``tests/test.sh``), so the
#: verifier only needs a Python to run its trivial reward writer.
_VERIFIER_BASE_IMAGE = "python:3.12-slim"

#: Agent and verifier timeouts (seconds, floats — Harbor's schema demands the ``.0``). The agent
#: gets an hour to read the help and build datapoints; the trivial verifier needs little.
_AGENT_TIMEOUT_SEC = 3600.0
_VERIFIER_TIMEOUT_SEC = 300.0

#: Names of the bundled package files copied into the build context so ``uv pip install -e .`` works.
_BUNDLED_PACKAGE_DIRNAME = "eval-harvest"

_TASK_DESCRIPTION = (
    "Build PR-review evaluation datapoints from this repository's pull-request history using the "
    "eval-harvest CLI, learning the workflow from the tool's own --help and man pages."
)

# The agent's ONLY guidance: the repo name and the PR to work from, plus "read the CLI's help". No
# methodology, no datapoint kind, no expected verdict — naming any of those would test the prompt
# rather than the CLI's documentation (PRD §4). ``{repo_url}``, ``{commit_sha}``, and ``{pr}`` are
# substituted per objective; nothing else varies.
_INSTRUCTION_TEMPLATE = """\
# Build PR-review evaluation datapoints

This container holds a checkout of {repo_url} pinned at commit `{commit_sha}`. The `eval-harvest`
command-line tool is installed.

Build PR-review evaluation datapoints from this repository's pull-request history with `eval-harvest`.
Learn how the tool works from its own documentation: run `eval-harvest --help`, then
`eval-harvest <verb> --help` for each verb it lists, and read its man pages. Follow the workflow the
tool describes.

Work from pull request #{pr}. Produce the datapoint(s) the tool's workflow yields for it, and leave
them in the dataset directory the tool writes to.
"""

# The agent environment: clone the repo at the pinned SHA, then editable-install the bundled package.
_DOCKERFILE_TEMPLATE = """\
# Generated by eval-harvest (Workstream G, G-1). The agent-under-test drives the eval-harvest CLI
# from its --help alone; this image gives it git, gh, uv, an editable eval_harvest, and the repo
# checked out at the objective's pinned commit.
FROM {base_image}

# git ships in python:3.12-bookworm; add gh (the CLI's forge client) and uv (the installer).
RUN curl -fsSL https://cli.github.com/packages/githubcli-archive-keyring.gpg \\
      -o /usr/share/keyrings/githubcli-archive-keyring.gpg \\
 && echo "deb [signed-by=/usr/share/keyrings/githubcli-archive-keyring.gpg] https://cli.github.com/packages stable main" \\
      > /etc/apt/sources.list.d/github-cli.list \\
 && apt-get update \\
 && apt-get install -y --no-install-recommends gh \\
 && rm -rf /var/lib/apt/lists/*
RUN pip install --no-cache-dir uv

# Editable-install eval_harvest from the source bundled into this build context (uv pip install -e .).
COPY {bundle} /opt/eval-harvest
RUN uv pip install --system -e /opt/eval-harvest

# Clone the target repository, pinned at the objective's commit SHA so the history cannot drift.
RUN git clone {repo_url} /work/repo \\
 && git -C /work/repo checkout {commit_sha}
WORKDIR /work
"""

# The eval's real grading is external — eval-harvest verify plus the G-2 quality judge and G-3
# metrics run over the captured trajectory, outside the VM. This in-VM verifier only needs to let
# `harbor run` complete, so it writes a neutral reward. Harbor discards the exit code and reads only
# the reward file (verifier/verifier.py:199-202), the same contract the emitted datapoints use.
_VERIFIER_TEST_SH = """\
#!/bin/sh
# Generated by eval-harvest (Workstream G). The eval is graded externally (eval-harvest verify +
# the G-2 quality judge + G-3 metrics over the captured trajectory), so this in-VM verifier only
# writes a neutral reward to let `harbor run` complete. Do not read a quality signal from it.
set -u
mkdir -p /logs/verifier
printf '{"reward": 0.0, "note": "graded externally by eval-harvest verify + G-2/G-3"}' \\
  > /logs/verifier/reward.json
exit 0
"""

_VERIFIER_DOCKERFILE = f"""\
FROM {_VERIFIER_BASE_IMAGE}

# In separate-verifier mode Harbor builds this image from tests/ and uploads nothing, so the
# verifier must be baked in (trial.py:612,686-693) — the same rule the emitted datapoints follow.
COPY --chmod=755 test.sh /tests/test.sh
"""


class EvalHarborTask:
    """Assembles and validates the eval's Harbor task directory for one objective. Holds no state."""

    @classmethod
    def materialize(cls, objective: Objective, destination: Path) -> Path:
        """Write the objective's Harbor task into ``destination`` and return it, or raise on an invalid shape.

        Assembles ``task.toml``, ``instruction.md``, ``environment/Dockerfile`` (+ the bundled
        ``eval_harvest`` source), and a trivial separate-mode ``tests/`` verifier, then validates the
        result with the shipped ``Harbor`` validators — dogfooding, and a real guard: a task Harbor
        would reject fails here rather than at ``harbor run``.
        """
        destination.mkdir(parents=True, exist_ok=True)
        cls._write_file(destination / "task.toml", cls.task_config_bytes(objective))
        cls._write_file(destination / "instruction.md", cls.instruction_text(objective).encode("utf-8"))
        cls._write_file(destination / "environment" / "Dockerfile", cls.dockerfile_text(objective).encode("utf-8"))
        cls._write_file(destination / "tests" / "Dockerfile", _VERIFIER_DOCKERFILE.encode("utf-8"))
        cls._write_file(destination / "tests" / "test.sh", _VERIFIER_TEST_SH.encode("utf-8"), executable=True)
        cls._bundle_package_source(destination / "environment" / _BUNDLED_PACKAGE_DIRNAME)
        cls._refuse_invalid(objective, destination)
        return destination

    # ───────────────────────────── the task.toml document ─────────────────────────────

    @classmethod
    def task_config_bytes(cls, objective: Objective) -> bytes:
        """The serialized ``task.toml`` for this objective (the agent env is ``public`` — it clones)."""
        return emit_document(cls.task_config_document(objective))

    @classmethod
    def task_config_document(cls, objective: Objective) -> dict[str, TomlValue]:
        """The ``task.toml`` value tree: single-step, ``separate`` verifier, ``public`` agent network.

        The agent environment is ``public`` because the CLI clones the repo and reaches GitHub via
        ``gh``; the verifier is ``no-network``. Provenance lives under ``[metadata.eval]`` — the only
        placement Harbor preserves (unknown top-level keys are silently dropped, harbor.py)."""
        return {
            "schema_version": TASK_SCHEMA_VERSION,
            "task": {
                "name": cls.task_name(objective),
                "version": "1.0.0",
                "description": _TASK_DESCRIPTION,
                "keywords": ["eval-harvest", "pr-review", "meta-eval"],
            },
            "agent": {"timeout_sec": TomlFloat(_AGENT_TIMEOUT_SEC)},
            "verifier": {
                "timeout_sec": TomlFloat(_VERIFIER_TIMEOUT_SEC),
                "environment_mode": "separate",
                "environment": {"network_mode": "no-network", "os": "linux"},
            },
            "environment": {"network_mode": "public", "os": "linux"},
            "metadata": {
                "eval": {
                    "objective_id": objective.id,
                    "repo_url": objective.repo_url,
                    "commit_sha": objective.commit_sha,
                    "pr": objective.pr,
                    "kind": objective.kind,
                }
            },
        }

    @staticmethod
    def task_name(objective: Objective) -> str:
        """Harbor's ``org/name`` id for the eval task, e.g. ``eval-harvest/pydantic-13611-reject``."""
        return f"eval-harvest/{objective.id}"

    # ───────────────────────────── the text templates ─────────────────────────────

    @staticmethod
    def instruction_text(objective: Objective) -> str:
        """The agent's instruction: repo + PR + "read the CLI's help", and nothing about the verdict."""
        return _INSTRUCTION_TEMPLATE.format(repo_url=objective.repo_url, commit_sha=objective.commit_sha, pr=objective.pr)

    @staticmethod
    def dockerfile_text(objective: Objective) -> str:
        """The agent-environment Dockerfile: clone at the pinned SHA and editable-install the package."""
        return _DOCKERFILE_TEMPLATE.format(
            base_image=_AGENT_BASE_IMAGE,
            bundle=_BUNDLED_PACKAGE_DIRNAME,
            repo_url=objective.repo_url,
            commit_sha=objective.commit_sha,
        )

    # ───────────────────────────── bundling & validation ─────────────────────────────

    @staticmethod
    def _bundle_package_source(destination: Path) -> None:
        """Copy the ``eval_harvest`` source (``src/`` + ``pyproject.toml``) into the build context.

        This is what makes ``uv pip install -e .`` in the Dockerfile a genuine editable install of
        the CLI under test, rather than a fetch of some published wheel — the eval runs the *local*
        package. ``__pycache__`` is skipped so the build context does not carry stale bytecode.
        """
        destination.mkdir(parents=True, exist_ok=True)
        shutil.copytree(
            _REPO_ROOT / "src",
            destination / "src",
            ignore=shutil.ignore_patterns("__pycache__", "*.pyc"),
            dirs_exist_ok=True,
        )
        shutil.copy2(_REPO_ROOT / "pyproject.toml", destination / "pyproject.toml")

    @classmethod
    def _refuse_invalid(cls, objective: Objective, destination: Path) -> None:
        """Raise if the assembled task fails Harbor's ``task.toml`` schema or its layout rules."""
        document = cls.task_config_document(objective)
        compiled = cls._compiled_task(destination)
        violations = Harbor.validate_task_config(document) + Harbor.validate_task_layout(compiled)
        if violations:
            detail = "; ".join(str(violation) for violation in violations)
            raise ValueError(f"eval Harbor task for {objective.id} is not Harbor-valid: {detail}")

    @staticmethod
    def _compiled_task(destination: Path) -> CompiledTask:
        """The assembled directory as ``Harbor.validate_task_layout`` reads it."""
        files = tuple(
            EmittedFile(path=path.relative_to(destination).as_posix())
            for path in sorted(destination.rglob("*"))
            if path.is_file()
        )
        return CompiledTask(name=destination.name, files=files, directory=destination.name, verifier_mode="separate")

    @staticmethod
    def _write_file(path: Path, data: bytes, *, executable: bool = False) -> None:
        """Write ``data`` to ``path``, creating parents and setting the exec bit when asked."""
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
        if executable:
            path.chmod(0o755)
